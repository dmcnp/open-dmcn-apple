#!/usr/bin/env python3
"""Regenerates the app's icon set from the web client's, so the two draw the same glyphs.

Reads the Lucide glyphs in open-dmcn's cmd/dmcnd/web/src/components/Icon.tsx and writes one
template image set per glyph into App/Resources/Assets.xcassets/Icons, plus the `Icon` enum in
App/Shared/DesignSystem/Icon.swift. Run it after the web client's set changes:

    dev/generate-icons.py [path to an open-dmcn checkout]
"""
import json
import pathlib
import re
import shutil
import sys

root = pathlib.Path(__file__).resolve().parent.parent
open_dmcn = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root.parent / "open-dmcn"
source = (open_dmcn / "cmd/dmcnd/web/src/components/Icon.tsx").read_text()
catalog = root / "App/Resources/Assets.xcassets/Icons"
swift = root / "App/Shared/DesignSystem/Icon.swift"

# The web passes strokeWidth={2.8} for the ticks and crosses in the checks strip. An asset's
# stroke is fixed, so those two get their own heavier sets.
HEAVY = {"check", "x"}

glyphs = {}
for line in source.splitlines():
    match = re.match(r"\s+'?([a-z-]+)'?: (<.*>),$", line)
    if match:
        glyphs[match.group(1)] = re.sub(r"^<>|</>$", "", match.group(2))


def write(name, body, stroke):
    body = body.replace("currentColor", "#000000")
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
        f'stroke="#000000" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>\n'
    )
    folder = catalog / f"icon-{name}.imageset"
    folder.mkdir(parents=True)
    (folder / f"{name}.svg").write_text(svg)
    (folder / "Contents.json").write_text(json.dumps({
        "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
        "info": {"author": "xcode", "version": 1},
        "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
    }, indent=2) + "\n")


shutil.rmtree(catalog, ignore_errors=True)
catalog.mkdir(parents=True)
(catalog / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
for name, body in glyphs.items():
    write(name, body, 2)
for name in HEAVY:
    write(name + "-heavy", glyphs[name], 2.8)


def case(name):
    head, *tail = name.split("-")
    word = head + "".join(part.capitalize() for part in tail)
    return f"`{word}`" if word in {"repeat", "in", "default", "case"} else word


names = sorted(list(glyphs) + [n + "-heavy" for n in HEAVY])
cases = "\n".join(f'    case {case(n)} = "icon-{n}"' for n in names)
swift.parent.mkdir(parents=True, exist_ok=True)
swift.write_text(f"""import SwiftUI

// Generated by dev/generate-icons.py from the web client's Icon.tsx. Don't edit by hand.

/// A glyph from the shared icon set: Lucide, 2px stroke, round caps, tinted by the foreground.
enum Icon: String, CaseIterable, Sendable {{
{cases}
}}

extension Icon {{
    /// The glyph at `size` points, in the current foreground colour.
    @MainActor func image(_ size: CGFloat = 18) -> some View {{
        Image(rawValue).renderingMode(.template).resizable().frame(width: size, height: size).accessibilityHidden(true)
    }}
}}
""")
print(f"wrote {len(names)} icons")
